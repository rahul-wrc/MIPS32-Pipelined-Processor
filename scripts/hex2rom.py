#!/usr/bin/env python3
"""Turn a program.mem ($readmemh style: one 32-bit hex word per line) into a
synthesizable ROM module `instruction_memory` (case statement, no $readmemh).

usage: python3 hex2rom.py program.mem rtl/instruction_memory.v
Unlisted addresses return 0x00000000 (a NOP), same as an all-zero memory.
"""
import re, sys

DEPTH = 256
words = []
for line in open(sys.argv[1]):
    line = line.split("//")[0].strip()
    if not line:
        continue
    if line.startswith("@"):
        sys.exit("'@addr' directives not supported; use one word per line")
    for tok in line.split():
        if not re.fullmatch(r"[0-9a-fA-F_]{1,8}", tok):
            sys.exit(f"bad hex word: {tok}")
        words.append(int(tok.replace("_", ""), 16))
if len(words) > DEPTH:
    sys.exit(f"program has {len(words)} words, max {DEPTH}")

out = ["// AUTO-GENERATED by scripts/hex2rom.py from %s - do not edit by hand." % sys.argv[1],
       "// Synthesizable instruction ROM (256 words). Unlisted words read as NOP.",
       "module instruction_memory (",
       "    input  wire [31:0] address,",
       "    output reg  [31:0] instruction",
       ");",
       "",
       "    always @(*) begin",
       "        case (address[9:2])"]
for i, w in enumerate(words):
    out.append("            8'd%-3d: instruction = 32'h%08X;" % (i, w))
out += ["            default: instruction = 32'h00000000;",
        "        endcase",
        "    end",
        "",
        "endmodule", ""]
open(sys.argv[2], "w").write("\n".join(out))
print(f"wrote {sys.argv[2]} ({len(words)} instructions)")
